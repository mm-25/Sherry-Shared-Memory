package dev.sherry.capture.core

import java.io.File
import kotlin.test.*

class CaptureTest {
    private val workspace = "7c895c18-05e4-4f96-9148-37ad93b2a789"
    private val device = "android-test-device"

    @Test fun `all providers produce valid partial v2 envelopes`() {
        val fixtures = Provider.entries.map { provider ->
            val capture = CaptureFactory.share(provider, "A useful response", "A test excerpt")
            val frozen = CaptureFactory.freeze(capture, workspace, device)
            val batch = CaptureJson.decodeFromString<CaptureBatch>(frozen.payload!!)
            assertEquals("android", batch.surface)
            assertEquals(provider.family, batch.providerFamily)
            assertEquals("unknown", batch.events.single().role)
            assertEquals("partial", batch.coverage.state)
            assertTrue(batch.coverage.gapBefore)
            assertNull(batch.events.single().providerMessageId)
            assertNull(batch.events.single().messageTimestamp)
            frozen.payload
        }
        // Consumed by the existing backend validator; generated by actual Kotlin code.
        File("build/contract-fixtures.json").apply { parentFile.mkdirs(); writeText(fixtures.joinToString(",", "[", "]")) }
    }

    @Test fun `native snapshots preserve roles order and retry identity without inventing provider IDs`() {
        val session = java.util.UUID.randomUUID().toString()
        val messages = listOf(ParsedMessage("user", "Again"), ParsedMessage("assistant", "Reply"), ParsedMessage("user", "Again"))
        val captures = CaptureFactory.nativeSnapshot(messages, session, ChatGptParser.VERIFIED_VERSION)
        assertEquals(listOf(0, 1, 2), captures.map { it.event.sequence })
        assertEquals(1, captures.map { it.event.conversationId }.distinct().size)
        assertEquals(3, captures.map { it.event.eventId }.distinct().size)
        assertTrue(captures.all { it.event.providerMessageId == null && it.event.sourceUrl == null })
        val next = CaptureFactory.nativeSnapshot(messages, java.util.UUID.randomUUID().toString(), ChatGptParser.VERIFIED_VERSION)
        assertNotEquals(captures[0].event.conversationId, next[0].event.conversationId)
        val payloads = captures.map { CaptureFactory.freeze(it, workspace, device).payload!! }
        payloads.forEach { payload ->
            val batch = CaptureJson.decodeFromString<CaptureBatch>(payload)
            assertEquals("accessibility", batch.reason)
            assertEquals("accessibility", batch.captureClient.type)
            assertEquals(session, batch.captureClient.captureSessionId)
            assertEquals(ChatGptParser.VERIFIED_VERSION, batch.captureClient.appVersion)
            assertEquals("partial", batch.coverage.state)
        }
        File("build/native-contract-fixtures.json").writeText(payloads.joinToString(",", "[", "]"))
    }

    @Test fun `retry and restart preserve exact body and idempotency key`() {
        val original = CaptureFactory.freeze(CaptureFactory.share(Provider.CHATGPT, "Keep this", "Title"), workspace, device)
        val restored = CaptureJson.decodeFromString<LocalCapture>(CaptureJson.encodeToString(LocalCapture.serializer(), original))
        val retried = CaptureFactory.freeze(restored, workspace, "different-device-after-restart")
        assertEquals(original.payload, retried.payload)
        assertEquals(original.id, retried.id)
        assertFailsWith<IllegalArgumentException> { CaptureFactory.freeze(restored, "7c895c18-05e4-4f96-9148-37ad93b2a780", device) }
    }

    @Test fun `shares remain distinct without inventing conversation identity`() {
        val first = CaptureFactory.share(Provider.CHATGPT, "Same text", "Same title")
        val second = CaptureFactory.share(Provider.CHATGPT, "Same text", "Same title")
        assertNotEquals(first.event.conversationId, second.event.conversationId)
        assertEquals(first.event.contentHash, second.event.contentHash)
    }

    @Test fun `links do not become fabricated transcripts`() {
        val link = "https://chatgpt.com/share/example"
        val capture = CaptureFactory.share(Provider.CHATGPT, link, "Shared link")
        assertEquals(link, capture.event.text)
        assertEquals(link, capture.event.sourceUrl)
        assertNull(CaptureFactory.providerLink(Provider.CHATGPT, "https://chatgpt.com.evil.test/share/x"))
        assertNull(CaptureFactory.providerLink(Provider.CHATGPT, "https://attacker@chatgpt.com/share/x"))
        assertNull(CaptureFactory.providerLink(Provider.CHATGPT, "https://claude.ai/share/x"))
    }

    @Test fun `blank oversized and invalid roles are rejected before persistence`() {
        assertFailsWith<IllegalArgumentException> { CaptureFactory.share(Provider.CHATGPT, "  ", "Title") }
        assertFailsWith<IllegalArgumentException> { CaptureFactory.share(Provider.CHATGPT, "x".repeat(60_001), "Title") }
        assertFailsWith<IllegalArgumentException> { CaptureFactory.share(Provider.CHATGPT, "Text", "Title", "system") }
        assertFailsWith<IllegalArgumentException> { CaptureFactory.freeze(CaptureFactory.share(Provider.CHATGPT, "Text", "Title"), "not-a-workspace", device) }
    }

    @Test fun `maximally escaped text stays inside server byte limit`() {
        val capture = CaptureFactory.share(Provider.CHATGPT, "x\u0001".repeat(30_000), "Title")
        val frozen = CaptureFactory.freeze(capture, workspace, device)
        assertTrue(frozen.payload!!.toByteArray().size <= 524_288)
    }

    @Test fun `only confirmed commits remove queued data`() {
        assertEquals(UploadDecision.COMMITTED, uploadDecision(200, true))
        assertEquals(UploadDecision.RETRY, uploadDecision(200, false))
        assertEquals(UploadDecision.AUTH_REQUIRED, uploadDecision(401, false))
        assertEquals(UploadDecision.AUTH_REQUIRED, uploadDecision(403, false))
        for (code in listOf(408, 429, 500, 503)) assertEquals(UploadDecision.RETRY, uploadDecision(code, false))
        for (code in listOf(302, 400, 409, 413, 422)) assertEquals(UploadDecision.REJECTED, uploadDecision(code, false))
    }

    @Test fun `acknowledgements match the batch and keep legacy deletion responses distinct`() {
        assertEquals(Acknowledgement.COMMITTED, acknowledgement("""{"ok":true,"batchId":"test","result":{"status":"committed","received":1,"inserted":1,"updated":0,"duplicates":0}}""", "test", 1))
        assertEquals(Acknowledgement.PREVIOUSLY_DELETED, acknowledgement("""{"ok":true,"batchId":"test","ignoredDeletedEvents":1}""", "test", 1))
        for (body in listOf(null, "bad json", """{"ok":true}""",
            """{"ok":true,"batchId":"other","result":{"status":"committed"}}""",
            """{"ok":true,"batchId":"test","result":{"status":"processing"}}""",
            """{"ok":true,"batchId":"test","ignoredDeletedEvents":0}""",
            """{"ok":true,"batchId":"test","result":[]}""")) {
            assertEquals(Acknowledgement.UNCONFIRMED, acknowledgement(body, "test", 1))
        }
    }

    @Test fun `committed upload accounts for every inserted updated and replayed event`() {
        for (counts in listOf(
            "\"received\":3,\"inserted\":1,\"updated\":1,\"duplicates\":1",
            "\"received\":3,\"inserted\":0,\"updated\":0,\"duplicates\":3",
            "\"received\":3.0,\"inserted\":1e0,\"updated\":1,\"duplicates\":1"
        )) {
            val body = """{"ok":true,"batchId":"test","result":{"status":"committed",$counts}}"""
            assertEquals(Acknowledgement.COMMITTED, acknowledgement(body, "test", 3))
        }
    }

    @Test fun `incomplete or malformed successful receipt keeps upload waiting`() {
        for (counts in listOf(
            "",
            ",\"received\":3",
            ",\"received\":2,\"inserted\":2,\"updated\":0,\"duplicates\":0",
            ",\"received\":3,\"inserted\":2,\"updated\":0,\"duplicates\":0",
            ",\"received\":\"3\",\"inserted\":3,\"updated\":0,\"duplicates\":0",
            ",\"received\":3,\"inserted\":-1,\"updated\":4,\"duplicates\":0",
            ",\"received\":3,\"inserted\":1.5,\"updated\":1.5,\"duplicates\":0",
            ",\"received\":3,\"inserted\":9223372036854775807,\"updated\":9223372036854775807,\"duplicates\":5",
            ",\"received\":3,\"inserted\":3,\"updated\":null,\"duplicates\":0"
        )) {
            val body = """{"ok":true,"batchId":"test","result":{"status":"committed"$counts}}"""
            val ack = acknowledgement(body, "test", 3)
            assertEquals(Acknowledgement.UNCONFIRMED, ack, body)
            assertEquals(UploadDecision.RETRY, uploadDecision(200, ack == Acknowledgement.COMMITTED), body)
        }
    }

    @Test fun `empty submitted batch cannot be confirmed`() {
        val body = """{"ok":true,"batchId":"test","result":{"status":"committed","received":0,"inserted":0,"updated":0,"duplicates":0}}"""
        assertEquals(Acknowledgement.UNCONFIRMED, acknowledgement(body, "test", 0))
    }

    @Test fun `streaming revisions settle before emitting once`() {
        val gate = StableTurnGate(1000)
        val turn = ObservedTurn("chat", "message", "assistant", "Final reply", false)
        assertNull(gate.observe(turn.copy(isStreaming = true), 0))
        assertNull(gate.observe(turn, 100))
        assertNull(gate.observe(turn, 1099))
        assertEquals(turn, gate.observe(turn, 1100))
        assertNull(gate.observe(turn, 3000))
        val edited = turn.copy(text = "Edited reply")
        assertNull(gate.observe(edited, 4000))
        assertEquals(edited, gate.observe(edited, 5000))
    }

    @Test fun `editable unknown and identityless nodes never become turns`() {
        val gate = StableTurnGate(0)
        val turn = ObservedTurn("chat", "message", "assistant", "Draft", false)
        for (bad in listOf(turn.copy(isEditable = true), turn.copy(role = "unknown"), turn.copy(conversationId = ""), turn.copy(messageId = ""))) {
            assertNull(gate.observe(bad, 0)); assertNull(gate.observe(bad, 1000))
        }
    }

    @Test fun `reappearing streaming state resets quiet interval`() {
        val gate = StableTurnGate(1000)
        val turn = ObservedTurn("chat", "message", "assistant", "Reply", false)
        gate.observe(turn, 0)
        gate.observe(turn.copy(isStreaming = true), 900)
        assertNull(gate.observe(turn, 1500))
        assertNull(gate.observe(turn, 2400))
        assertEquals(turn, gate.observe(turn, 2500))
    }
}
